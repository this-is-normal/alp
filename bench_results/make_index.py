#!/usr/bin/env python3
"""Regenerate INDEX.md from the JSON sidecars.

The narrative lives in the `.md`; the numbers live in the `.json` so they can be
sorted and diffed without parsing prose.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
rows = []
for path in sorted(HERE.glob("*.json"), reverse=True):
    d = json.loads(path.read_text())
    rows.append(
        (
            d.get("date", "?"),
            d.get("layer", "?"),
            d.get("target", "?"),
            d.get("headline", ""),
            d.get("host", "?"),
            f"[{path.stem}]({path.with_suffix('.md').name})",
        )
    )

out = [
    "# Index",
    "",
    "Generated by `make_index.py` — do not edit. Newest first.",
    "",
    "| date | layer | target | headline | box | record |",
    "|---|---|---|---|---|---|",
]
out += ["| " + " | ".join(r) + " |" for r in rows]
out.append("")
(HERE / "INDEX.md").write_text("\n".join(out))
print(f"wrote INDEX.md with {len(rows)} record(s)")
